// إعداداتُ الموقع العامّة — عنوانُه ووسائطُه، تُقرأ من متغيّرات البيئة.
//
// العنوان أصلُ الوسوم كلِّها (canonical وOpen Graph وsitemap)، فيُقرأ من
// NEXT_PUBLIC_SITE_URL وقتَ البناء. وما لم يُضبط يسقط إلى localhost — عنوانٌ
// صالحٌ للتطوير لا يكسر شيئًا، ويُستبدل في الإنتاج من .env. راجع .env.example.

/** عنوانُ الموقع بلا شرطةٍ مائلةٍ في آخره — أساسُ كلِّ رابطٍ مطلق */
export const SITE_URL = (
  process.env.NEXT_PUBLIC_SITE_URL || "http://localhost:3000"
).replace(/\/$/, "");

// ــــــــ اسمُ العلامة: ثابتٌ واحدٌ لا يُكرَّر نصًّا في مكانٍ آخر ــــــــ
// كان الاسمُ مكتوبًا يدًا في الترويسة والتذييل وشاشة الترحيب وجدول اللغات،
// فاختلفت النسخُ («فالوري بارفوم» في تذييلٍ عربيّ و«VALORY PARFUMES» في
// لاتينيّ، و«VALORY Parfumes» في الترويسة). صار المصدرُ هنا وحده.

/** اسمُ الدار باللاتينية — كما يُكتب في العلامة والوسوم */
export const SITE_NAME = "VALORY PARFUMES";

/** اسمُ الدار بالعربية — لصفحاتٍ ووسومٍ عربية */
export const SITE_NAME_AR = "فالوري";

/** العلامةُ المرسومة بسطرين كما في الشعار: الاسمُ فوق والصفةُ تحته.
 *  تُشتقّ من SITE_NAME فلا تفترق عنه إن تغيّر. */
export const BRAND_MARK = (() => {
  const [lead, ...rest] = SITE_NAME.split(" ");
  const tail = rest.join(" ");
  // «PARFUMES» تُرسم بحرفٍ كبيرٍ أوّلَ وصغيرٍ بعده كما في الشعار المرسوم.
  return {
    lead,
    tail: tail.charAt(0) + tail.slice(1).toLowerCase(),
  };
})();

/** عنوانُ الصفحة الأولى — يُعاد استعماله في الوسوم وفي القالب */
export const SITE_TITLE = `${SITE_NAME_AR} | ${SITE_NAME} — فنُّ العِطر`;

/** وصفُ الموقع العامّ. نجامينا وحدها: فرعُ الدوحة لم يُفتح بعدُ ولا
 *  بياناتٍ له، فلا يُذكر في وصفٍ يقرؤه الزبونُ ومحرّكُ البحث. */
export const SITE_DESCRIPTION =
  "فالوري — متجرُ عطورٍ مختارة في نجامينا، نجمع لك أفضلَ العطور الشرقية والعالمية بأسعار الفرع.";

/** صورةُ المشاركة الافتراضية (1200×630) — لكلِّ صفحةٍ لا صورةَ لها */
export const OG_IMAGE = "/og-default.jpg";

/** رابطٌ مطلقٌ من مسارٍ نسبيّ — يجمع العنوانَ بالمسار بلا شرطتين */
export const absoluteUrl = (path = "/") =>
  `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`;

/** نطاقُ التحليلات (Plausible) إن فُعِّل — بلا قيمةٍ لا يُحمَّل أيُّ سكربت */
export const ANALYTICS_DOMAIN = process.env.NEXT_PUBLIC_ANALYTICS_DOMAIN || "";
